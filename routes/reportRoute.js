import express from "express";
import db from "../src/config/db.js";
import checkAdmin from "../middleware/checkAdmin.js";

const router = express.Router();

// Apply admin authorization to all report routes
router.use(checkAdmin);


// 1. Payment status of each order
router.get("/payments", async (req, res) => {
    try {
        const [rows] = await db.query(`
            SELECT
                O.OrderID,
                O.TotalAmount,
                P.AmountPaid,
                P.PaymentMethod,
                P.PaymentStatus
            FROM Orders O
            LEFT JOIN Payment P
                ON O.OrderID = P.OrderID
            ORDER BY O.OrderID DESC
        `);

        res.status(200).json({
            success: true,
            data: rows
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({
            success: false,
            message: "Failed to retrieve payment report."
        });
    }
});


// 2. Most frequently ordered menu items
router.get("/popular-dishes", async (req, res) => {
    try {
        const [rows] = await db.query(`
            SELECT
                M.ItemID,
                M.ItemName,
                SUM(OD.Quantity) AS TotalQuantitySold
            FROM MenuItem M
            INNER JOIN OrderDetails OD
                ON M.ItemID = OD.ItemID
            GROUP BY M.ItemID, M.ItemName
            ORDER BY TotalQuantitySold DESC
        `);

        res.status(200).json({
            success: true,
            data: rows
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({
            success: false,
            message: "Failed to retrieve popular dishes."
        });
    }
});


// 3. Menu items that have never been ordered
router.get("/never-ordered", async (req, res) => {
    try {
        const [rows] = await db.query(`
            SELECT
                M.ItemID,
                M.ItemName,
                M.Price
            FROM MenuItem M
            LEFT JOIN OrderDetails OD
                ON M.ItemID = OD.ItemID
            WHERE OD.ItemID IS NULL
            ORDER BY M.ItemName
        `);

        res.status(200).json({
            success: true,
            data: rows
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({
            success: false,
            message: "Failed to retrieve never-ordered items."
        });
    }
});


// 4. Number of orders created by each staff member
router.get("/staff-performance", async (req, res) => {
    try {
        const [rows] = await db.query(`
            SELECT
                S.StaffID,
                S.Name AS StaffName,
                S.Role,
                COUNT(O.OrderID) AS TotalOrders
            FROM Staff S
            LEFT JOIN Orders O
                ON S.StaffID = O.StaffID
            GROUP BY S.StaffID, S.Name, S.Role
            ORDER BY TotalOrders DESC
        `);

        res.status(200).json({
            success: true,
            data: rows
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({
            success: false,
            message: "Failed to retrieve staff performance."
        });
    }
});


// 5. Revenue generated by each menu item
router.get("/dish-revenue", async (req, res) => {
    try {
        const [rows] = await db.query(`
            SELECT
                M.ItemID,
                M.ItemName,
                SUM(OD.Quantity) AS TotalQuantitySold,
                SUM(OD.Subtotal) AS TotalSales
            FROM MenuItem M
            INNER JOIN OrderDetails OD
                ON M.ItemID = OD.ItemID
            GROUP BY M.ItemID, M.ItemName
            ORDER BY TotalSales DESC
        `);

        res.status(200).json({
            success: true,
            data: rows
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({
            success: false,
            message: "Failed to retrieve dish revenue."
        });
    }
});


// 6. Current stock of all ingredients
router.get("/inventory", async (req, res) => {
    try {
        const [rows] = await db.query(`
            SELECT
                IngredientID,
                IngredientName,
                QuantityInStock,
                Unit,
                ReorderLevel,
                CASE
                    WHEN QuantityInStock <= ReorderLevel
                    THEN 'Reorder Required'
                    ELSE 'In Stock'
                END AS StockStatus
            FROM Ingredient
            ORDER BY IngredientName
        `);

        res.status(200).json({
            success: true,
            data: rows
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({
            success: false,
            message: "Failed to retrieve inventory."
        });
    }
});


// 7. Ingredients that need replenishment
router.get("/low-stock", async (req, res) => {
    try {
        const [rows] = await db.query(`
            SELECT
                IngredientID,
                IngredientName,
                QuantityInStock,
                Unit,
                ReorderLevel
            FROM Ingredient
            WHERE QuantityInStock <= ReorderLevel
            ORDER BY QuantityInStock ASC
        `);

        res.status(200).json({
            success: true,
            data: rows
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({
            success: false,
            message: "Failed to retrieve low-stock report."
        });
    }
});

export default router;
